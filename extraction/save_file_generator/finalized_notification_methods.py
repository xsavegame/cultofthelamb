        "    if (this === null || this === undefined) {",
        "      return null;",
        "    }",
        "",
        "    const rawWire = MessagePackObject.prototype.toMsgPackObject.call(this);",
        "    const payload = FinalizedNotification.unwrapUnionPayload(rawWire);",
        "",
        "    let tag = FinalizedNotification.tryMapCtorNameToTag(",
        "      (this as any)?.constructor?.name,",
        "    );",
        "",
        "    if (tag === null) {",
        "      const unionTag = FinalizedNotification.tryReadUnionTag(rawWire);",
        "      tag = FinalizedNotification.mapUnionTagToPolymorphicTag(unionTag);",
        "    }",
        "",
        "    if (tag === null) {",
        "      throw new Error(",
        "        `Unsupported FinalizedNotification subtype: ${(this as any)?.constructor?.name ?? 'unknown'}`,",
        "      );",
        "    }",
        "",
        "    return [tag, payload];",
        "  }",
        "",
        "  public static createFromMsgPackObject<T extends MessagePackObject>(",
        "    this: new () => T,",
        "    obj: any,",
        "  ): T | null {",
        "    return FinalizedNotification.deserializePolymorphic(obj) as unknown as T | null;",
        "  }",
