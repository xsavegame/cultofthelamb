        "  }",
        "",
        "  private static deserializePolymorphic(",
        "    source: any,",
        "  ): FinalizedNotification | null {",
        "    if (source === null || source === undefined) {",
        "      return null;",
        "    }",
        "",
        "    if (!Array.isArray(source)) {",
        "      return null;",
        "    }",
        "",
        "    if (source.length < 2) {",
        "      throw new Error('FinalizedNotification: expected array with >= 2 items.');",
        "    }",
        "",
        "    const tag = FinalizedNotification.tryParsePolymorphicTag(source[0]);",
        "    if (tag === null) {",
        "      return null;",
        "    }",
        "",
        "    const payloadIndex = source.length >= 3 ? 2 : 1;",
        "    const payload = FinalizedNotification.decodePossiblyCompressedPayload(",
        "      source[payloadIndex],",
        "    );",
        "",
        "    const unionTag = FinalizedNotification.mapPolymorphicTagToUnionTag(tag);",
        "    if (unionTag === null) {",
        "      return null;",
        "    }",
        "",
        "    return MessagePackObject.createFromMsgPackObject.call(",
        "      FinalizedNotification as unknown as typeof MessagePackObject,",
        "      [unionTag, payload],",
        "    ) as unknown as FinalizedNotification | null;",
        "  }",
        "",
        "  private static tryReadUnionTag(value: any): number | null {",
        "    if (!Array.isArray(value) || value.length < 2) {",
        "      return null;",
        "    }",
        "    return FinalizedNotification.tryCoerceTagNumber(value[0]);",
        "  }",
        "",
