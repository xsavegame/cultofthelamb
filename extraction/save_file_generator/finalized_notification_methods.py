        "  public static createFromJSON<T extends MessagePackObject>(",
        "    this: new () => T,",
        "    json: any,",
        "  ): T | null {",
        "    if (json === null || json === undefined) {",
        "      return null;",
        "    }",
        "",
        "    if (Array.isArray(json)) {",
        "      return FinalizedNotification.deserializePolymorphic(json) as unknown as T | null;",
        "    }",
        "",
        "    return MessagePackObject.createFromJSON.call(",
        "      FinalizedNotification as unknown as typeof MessagePackObject,",
        "      json,",
