        "    }",
        "  }",
        "",
        "  private static mapUnionTagToPolymorphicTag(tag: number | null): number | null {",
        "    switch (tag) {",
        "      case 4:",
        "        return FinalizedNotification.TAG_BASE;",
        "      case 0:",
        "        return FinalizedNotification.TAG_FAITH;",
        "      case 1:",
        "        return FinalizedNotification.TAG_ITEM;",
