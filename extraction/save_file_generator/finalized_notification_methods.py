        "    if (Array.isArray(value) && value.length >= 2) {",
        "      const maybeTag = FinalizedNotification.tryCoerceTagNumber(value[0]);",
        "      if (maybeTag !== null) {",
        "        return value[1];",
        "      }",
        "    }",
        "    return value;",
        "  }",
        "",
