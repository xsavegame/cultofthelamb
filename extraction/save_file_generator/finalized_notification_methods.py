        "        return FinalizedNotification.TAG_FAITH;",
        "      case 'item':",
        "        return FinalizedNotification.TAG_ITEM;",
        "      case 'follower':",
        "        return FinalizedNotification.TAG_FOLLOWER;",
        "      case 'relationship':",
        "        return FinalizedNotification.TAG_RELATIONSHIP;",
        "      case 'base':",
        "      case 'simple':",
        "        return FinalizedNotification.TAG_BASE;",
        "      default:",
        "        return null;",
        "    }",
        "  }",
        "",
        "  private static tryCoerceTagNumber(value: unknown): number | null {",
        "    let numeric: number;",
        "    if (typeof value === 'bigint') {",
        "      numeric = Number(value);",
        "    } else if (typeof value === 'number') {",
        "      numeric = value;",
        "    } else if (typeof value === 'string') {",
        "      const parsed = Number(value);",
        "      if (!Number.isFinite(parsed)) {",
        "        return null;",
        "      }",
        "      numeric = parsed;",
        "    } else {",
        "      return null;",
        "    }",
        "",
        "    if (!Number.isInteger(numeric)) {",
        "      return null;",
        "    }",
        "",
        "    if (numeric < FinalizedNotification.TAG_BASE || numeric > FinalizedNotification.TAG_RELATIONSHIP) {",
